func isOptionParameter(fn TLType, p TLParam) bool {
	if len(fn.Params) <= 1 {
		return false
	}
	if p.IsOptional || p.Type == "Bool" {
		return true
	}
	switch p.Type {
	case "int32", "int53", "int64", "string":
		return slices.Contains(zeroDefaultParameters[fn.Name], p.Name)
	default:
		return false
	}
}

func hasOptionParameters(fn TLType) bool {
	for _, p := range fn.Params {
		if isOptionParameter(fn, p) {
			return true
		}
	}
	return false
}
